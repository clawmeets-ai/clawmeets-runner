# Image edit / compose backends (image-conditioned generation)
# --------------------------------------------------------------------------- #
def _image_edit_openai(
    cfg: dict, prompt: str, size: str, quality: str, input_images: list[str]
) -> bytes:
    """gpt-image-2 edit/compose via multipart POST to /v1/images/edits.

    One ``image[]`` file part per input (order preserved: first = subject, later
    = background/reference). Returns decoded ``b64_json`` bytes. 4xx surfaces the
    provider message verbatim.
    """
    import httpx

    files = []
    for path in input_images:
        raw, mime, name = _load_input_image(path)
        files.append(("image[]", (name, raw, mime)))
    data = {"model": cfg["model"], "prompt": prompt, "size": size, "quality": quality, "n": "1"}
    headers = {"Authorization": f"Bearer {cfg['api_key']}"}  # httpx sets multipart Content-Type
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(OPENAI_IMAGE_EDITS_URL, data=data, files=files, headers=headers)
    if resp.status_code >= 400:
        raise RuntimeError(f"OpenAI Images edit API returned {resp.status_code}: {_err_msg(resp)}")
    out = (resp.json().get("data") or [])
    if not out:
        raise RuntimeError(f"OpenAI Images edit API returned no data: {resp.json()!r}")
    b64 = out[0].get("b64_json")
    if not b64:
        raise RuntimeError("OpenAI Images edit response missing `b64_json`; check `model`.")
    return base64.b64decode(b64)


def _image_edit_nano_banana(cfg: dict, prompt: str, input_images: list[str]) -> bytes:
    """Gemini 2.5 Flash Image edit/compose via generateContent.

    Sends ``contents.parts = [{text: prompt}, {inline_data: {...}} per input]``
    and extracts the returned image via ``_extract_gemini_image`` (which also
    maps a text-only refusal to a RuntimeError).
    """
    import httpx

    parts: list[dict] = [{"text": prompt}]
    for path in input_images:
        raw, mime, _ = _load_input_image(path)
        parts.append({"inline_data": {"mime_type": mime, "data": base64.b64encode(raw).decode("ascii")}})
    url = f"{GEMINI_BASE_URL}/{cfg['model']}:generateContent"
    body = {"contents": [{"parts": parts}]}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, params={"key": cfg["api_key"]}, json=body,
                           headers={"Content-Type": "application/json"})
    if resp.status_code >= 400:
        raise RuntimeError(f"Gemini generateContent returned {resp.status_code}: {_err_msg(resp)}")
    return _extract_gemini_image(resp.json())


def generate_image(
    *, prompt: str, config_file: str = "", provider: str = "", model: str = "",
    api_key: str = "", output_dir: str = "", size: str = "", quality: str = "",
    input_images: list[str] | None = None,
) -> dict:
    if not isinstance(prompt, str) or not prompt.strip():
        raise RuntimeError("`prompt` is required and must be non-empty")
    cfg = load_config("image", config_file, {
        "provider": provider, "model": model, "api_key": api_key, "output_dir": output_dir,
    })
    provider = cfg["provider"]
    resolved_size = size or cfg["default_size"] or ("1:1" if provider == "gemini" else "1024x1024")
    resolved_quality = quality or cfg["default_quality"] or "auto"
    inputs = [p for p in (input_images or []) if isinstance(p, str) and p.strip()]

    if inputs:
        # Image-conditioned editing / compositing.
        if provider not in IMAGE_EDIT_PROVIDERS:
            raise RuntimeError(
                f"media image: provider {provider!r} does not support --input-image "
                f"editing; use --provider openai or nano-banana "
                f"(nano-banana is stronger for multi-image / background swaps).")
        if provider == "openai":
            if resolved_size not in OPENAI_SIZES:
                raise RuntimeError(
                    f"size {resolved_size!r} not supported by gpt-image-2; choose one of: {sorted(OPENAI_SIZES)}")
            if resolved_quality not in OPENAI_QUALITIES:
                raise RuntimeError(
                    f"quality {resolved_quality!r} not supported by gpt-image-2; choose one of: {sorted(OPENAI_QUALITIES)}")
            data = _image_edit_openai(cfg, prompt, resolved_size, resolved_quality, inputs)
        else:  # nano-banana
            data = _image_edit_nano_banana(cfg, prompt, inputs)
            resolved_size = resolved_size or "model-default"
            resolved_quality = "n/a"
        return _finalize(cfg, prompt, data, "png", {
            "mode": "edit", "size_used": resolved_size, "quality_used": resolved_quality,
            "input_images_used": inputs,
        })

    if provider == "openai":
        if resolved_size not in OPENAI_SIZES:
            raise RuntimeError(
                f"size {resolved_size!r} not supported by gpt-image-2; choose one of: {sorted(OPENAI_SIZES)}")
        if resolved_quality not in OPENAI_QUALITIES:
            raise RuntimeError(
                f"quality {resolved_quality!r} not supported by gpt-image-2; choose one of: {sorted(OPENAI_QUALITIES)}")
        data = _image_openai(cfg, prompt, resolved_size, resolved_quality)
    elif provider == "gemini":
        if resolved_size not in GEMINI_ASPECTS:
            raise RuntimeError(
                f"size {resolved_size!r} is not a valid Imagen aspect ratio; choose one of: {sorted(GEMINI_ASPECTS)}")
        data = _image_gemini(cfg, prompt, resolved_size)
        resolved_quality = "n/a"
    else:  # nano-banana
        data = _image_nano_banana(cfg, prompt)
        resolved_size = resolved_size or "model-default"
        resolved_quality = "n/a"

    return _finalize(cfg, prompt, data, "png",
                     {"mode": "generate", "size_used": resolved_size, "quality_used": resolved_quality})


