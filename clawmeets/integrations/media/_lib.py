def _audio_openai(cfg: dict, prompt: str, voice: str, fmt: str) -> tuple[bytes, str]:
    import httpx

    fmt = fmt or "mp3"
    body = {"model": cfg["model"], "input": prompt, "voice": voice or "alloy", "response_format": fmt}
    headers = {"Authorization": f"Bearer {cfg['api_key']}", "Content-Type": "application/json"}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(OPENAI_SPEECH_URL, json=body, headers=headers)
    if resp.status_code >= 400:
        raise RuntimeError(f"OpenAI Speech API returned {resp.status_code}: {_err_msg(resp)}")
    return resp.content, fmt


def _audio_elevenlabs(cfg: dict, prompt: str, voice: str, fmt: str) -> tuple[bytes, str]:
    import httpx

    voice_id = voice or ELEVENLABS_DEFAULT_VOICE
    url = f"{ELEVENLABS_BASE}/{voice_id}"
    body = {"text": prompt, "model_id": cfg["model"]}
    headers = {"xi-api-key": cfg["api_key"], "Content-Type": "application/json"}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, params={"output_format": "mp3_44100_128"}, json=body, headers=headers)
    if resp.status_code >= 400:
        raise RuntimeError(f"ElevenLabs TTS API returned {resp.status_code}: {_err_msg(resp)}")
    return resp.content, "mp3"


def _audio_gemini(cfg: dict, prompt: str, voice: str) -> tuple[bytes, str]:
    import httpx

    url = f"{GEMINI_BASE_URL}/{cfg['model']}:generateContent"
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "responseModalities": ["AUDIO"],
            "speechConfig": {"voiceConfig": {"prebuiltVoiceConfig": {"voiceName": voice or "Kore"}}},
        },
    }
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, params={"key": cfg["api_key"]}, json=body,
                           headers={"Content-Type": "application/json"})
    if resp.status_code >= 400:
        raise RuntimeError(f"Gemini TTS returned {resp.status_code}: {_err_msg(resp)}")
    candidates = (resp.json().get("candidates") or [])
    if not candidates:
        raise RuntimeError(f"Gemini TTS returned no candidates: {resp.json()!r}")
    parts = (candidates[0].get("content") or {}).get("parts") or []
    for part in parts:
        inline = part.get("inline_data") or part.get("inlineData") or {}
        mime = inline.get("mime_type") or inline.get("mimeType") or ""
        data_b64 = inline.get("data")
        if isinstance(mime, str) and mime.startswith("audio/") and data_b64:
            rate = 24000
            for tok in mime.split(";"):
                tok = tok.strip()
                if tok.startswith("rate="):
                    try:
                        rate = int(tok.split("=", 1)[1])
                    except ValueError:
                        pass
            return _pcm_to_wav(base64.b64decode(data_b64), rate), "wav"
    raise RuntimeError(f"Gemini TTS response had no audio part: {candidates[0]!r}")


def generate_audio(
    *, prompt: str, config_file: str = "", provider: str = "", model: str = "",
    api_key: str = "", output_dir: str = "", voice: str = "", audio_format: str = "",
) -> dict:
    if not isinstance(prompt, str) or not prompt.strip():
        raise RuntimeError("`prompt` is required and must be non-empty")
    cfg = load_config("audio", config_file, {
        "provider": provider, "model": model, "api_key": api_key, "output_dir": output_dir,
    })
    provider = cfg["provider"]
    resolved_voice = voice or cfg["voice"]
    resolved_fmt = audio_format or cfg["audio_format"]

    if provider == "openai":
        data, ext = _audio_openai(cfg, prompt, resolved_voice, resolved_fmt)
    elif provider == "elevenlabs":
        data, ext = _audio_elevenlabs(cfg, prompt, resolved_voice, resolved_fmt)
    else:  # gemini
        data, ext = _audio_gemini(cfg, prompt, resolved_voice)

    return _finalize(cfg, prompt, data, ext,
                     {"voice_used": resolved_voice or "default", "format_used": ext})


