def _video_replicate(cfg: dict, prompt: str, duration: str, aspect_ratio: str, input_image: str) -> tuple[bytes, str]:
    import httpx

    model = cfg["model"]
    if not model:
        raise RuntimeError(
            "video provider 'replicate' requires --model (an owner/name slug, "
            "e.g. 'google/veo-3', or a version id).")
    inp: dict[str, Any] = {"prompt": prompt}
    if duration:
        inp["duration"] = _maybe_number(duration)
    if aspect_ratio:
        inp["aspect_ratio"] = aspect_ratio
    if input_image:
        inp["image"] = _data_uri(input_image)

    headers = {"Authorization": f"Bearer {cfg['api_key']}", "Content-Type": "application/json"}
    if "/" in model and ":" not in model:
        url = f"{REPLICATE_BASE}/models/{model}/predictions"
        body: dict[str, Any] = {"input": inp}
    else:
        url = f"{REPLICATE_BASE}/predictions"
        body = {"version": model.split(":")[-1], "input": inp}

    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, json=body, headers=headers)
        if resp.status_code >= 400:
            raise RuntimeError(f"Replicate API returned {resp.status_code}: {_err_msg(resp)}")
        pred = resp.json()
        get_url = (pred.get("urls") or {}).get("get")
        status = pred.get("status")
        deadline = time.time() + cfg["timeout_seconds"]
        while status in ("starting", "processing") and get_url and time.time() < deadline:
            time.sleep(cfg["poll_interval_seconds"])
            pred = client.get(get_url, headers=headers).json()
            status = pred.get("status")
        if status != "succeeded":
            raise RuntimeError(f"Replicate prediction {status}: {pred.get('error') or pred!r}")
        output = pred.get("output")
        out_url = output[0] if isinstance(output, list) and output else output
        if not isinstance(out_url, str) or not out_url:
            raise RuntimeError(f"Replicate prediction had no output URL: {pred!r}")
        vid = client.get(out_url)
        if vid.status_code >= 400:
            raise RuntimeError(f"Replicate output download returned {vid.status_code}")
        return vid.content, _ext_from_url(out_url, "mp4")


def _dig_video_url(result: Any) -> str:
    """Best-effort extraction of a video URL from a fal result payload."""
    if isinstance(result, dict):
        vid = result.get("video")
        if isinstance(vid, dict) and isinstance(vid.get("url"), str):
            return vid["url"]
        for key in ("video_url", "url"):
            if isinstance(result.get(key), str):
                return result[key]
        videos = result.get("videos")
        if isinstance(videos, list) and videos and isinstance(videos[0], dict):
            if isinstance(videos[0].get("url"), str):
                return videos[0]["url"]
    raise RuntimeError(f"fal result had no recognizable video URL: {result!r}")


def _video_fal(cfg: dict, prompt: str, duration: str, aspect_ratio: str, input_image: str) -> tuple[bytes, str]:
    import httpx

    model = cfg["model"]
    if not model:
        raise RuntimeError(
            "video provider 'fal' requires --model (a fal-ai slug, e.g. "
            "'fal-ai/kling-video/v1/standard/text-to-video').")
    inp: dict[str, Any] = {"prompt": prompt}
    if duration:
        inp["duration"] = str(duration)
    if aspect_ratio:
        inp["aspect_ratio"] = aspect_ratio
    if input_image:
        inp["image_url"] = _data_uri(input_image)

    headers = {"Authorization": f"Key {cfg['api_key']}", "Content-Type": "application/json"}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(f"{FAL_QUEUE_BASE}/{model}", json=inp, headers=headers)
        if resp.status_code >= 400:
            raise RuntimeError(f"fal API returned {resp.status_code}: {_err_msg(resp)}")
        q = resp.json()
        status_url = q.get("status_url")
        response_url = q.get("response_url")
        status = q.get("status")
        deadline = time.time() + cfg["timeout_seconds"]
        while status not in ("COMPLETED", "ERROR", "FAILED") and status_url and time.time() < deadline:
            time.sleep(cfg["poll_interval_seconds"])
            status = client.get(status_url, headers=headers).json().get("status")
        if status != "COMPLETED":
            raise RuntimeError(f"fal request ended with status {status!r}")
        result = client.get(response_url, headers=headers).json()
        out_url = _dig_video_url(result)
        vid = client.get(out_url)
        if vid.status_code >= 400:
            raise RuntimeError(f"fal output download returned {vid.status_code}")
        return vid.content, _ext_from_url(out_url, "mp4")


def generate_video(
    *, prompt: str, config_file: str = "", provider: str = "", model: str = "",
    api_key: str = "", output_dir: str = "", duration: str = "",
    aspect_ratio: str = "", input_image: str = "",
) -> dict:
    if not isinstance(prompt, str) or not prompt.strip():
        raise RuntimeError("`prompt` is required and must be non-empty")
    cfg = load_config("video", config_file, {
        "provider": provider, "model": model, "api_key": api_key, "output_dir": output_dir,
    })
    provider = cfg["provider"]
    if provider == "replicate":
        data, ext = _video_replicate(cfg, prompt, duration, aspect_ratio, input_image)
    else:  # fal
        data, ext = _video_fal(cfg, prompt, duration, aspect_ratio, input_image)

    return _finalize(cfg, prompt, data, ext, {
        "duration_used": duration or "model-default",
        "aspect_ratio_used": aspect_ratio or "model-default",
    })
