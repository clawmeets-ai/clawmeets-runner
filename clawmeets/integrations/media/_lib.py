def _image_openai(cfg: dict, prompt: str, size: str, quality: str) -> bytes:
    import httpx

    body = {"model": cfg["model"], "prompt": prompt, "size": size, "quality": quality, "n": 1}
    headers = {"Authorization": f"Bearer {cfg['api_key']}", "Content-Type": "application/json"}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(OPENAI_IMAGES_URL, json=body, headers=headers)
    if resp.status_code >= 400:
        raise RuntimeError(f"OpenAI Images API returned {resp.status_code}: {_err_msg(resp)}")
    data = (resp.json().get("data") or [])
    if not data:
        raise RuntimeError(f"OpenAI Images API returned no data: {resp.json()!r}")
    b64 = data[0].get("b64_json")
    if not b64:
        raise RuntimeError("OpenAI Images API response missing `b64_json`; check `model`.")
    return base64.b64decode(b64)


def _image_gemini(cfg: dict, prompt: str, aspect: str) -> bytes:
    import httpx

    url = f"{GEMINI_BASE_URL}/{cfg['model']}:predict"
    body = {"instances": [{"prompt": prompt}], "parameters": {"sampleCount": 1, "aspectRatio": aspect}}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, params={"key": cfg["api_key"]}, json=body,
                           headers={"Content-Type": "application/json"})
    if resp.status_code >= 400:
        raise RuntimeError(f"Gemini Imagen API returned {resp.status_code}: {_err_msg(resp)}")
    preds = (resp.json().get("predictions") or [])
    if not preds:
        raise RuntimeError(f"Gemini Imagen API returned no predictions: {resp.json()!r}")
    b64 = preds[0].get("bytesBase64Encoded")
    if not b64:
        raise RuntimeError(
            f"Gemini Imagen response missing image bytes; likely a safety filter "
            f"rejection. Full prediction: {preds[0]!r}"
        )
    return base64.b64decode(b64)


def _extract_gemini_image(resp_json: dict) -> bytes:
    """Pull the first ``image/*`` part out of a Gemini generateContent payload.

    Shared by the text-to-image and edit/compose nano-banana paths. Raises
    ``RuntimeError`` on no candidates, a text-only (refusal) response, or a
    response with no image part.
    """
    candidates = (resp_json.get("candidates") or [])
    if not candidates:
        raise RuntimeError(f"Gemini generateContent returned no candidates: {resp_json!r}")
    parts = (candidates[0].get("content") or {}).get("parts") or []
    for part in parts:
        inline = part.get("inline_data") or part.get("inlineData") or {}
        mime = inline.get("mime_type") or inline.get("mimeType") or ""
        data_b64 = inline.get("data")
        if isinstance(mime, str) and mime.startswith("image/") and data_b64:
            return base64.b64decode(data_b64)
    text_parts = [p.get("text") for p in parts if p.get("text")]
    if text_parts:
        raise RuntimeError(
            "Gemini nano-banana returned text instead of an image (likely a "
            f"refusal): {' '.join(text_parts)[:300]}"
        )
    raise RuntimeError(f"Gemini nano-banana response had no image part: {candidates[0]!r}")


def _image_nano_banana(cfg: dict, prompt: str) -> bytes:
    import httpx

    url = f"{GEMINI_BASE_URL}/{cfg['model']}:generateContent"
    body = {"contents": [{"parts": [{"text": prompt}]}]}
    with httpx.Client(timeout=cfg["timeout_seconds"]) as client:
        resp = client.post(url, params={"key": cfg["api_key"]}, json=body,
                           headers={"Content-Type": "application/json"})
    if resp.status_code >= 400:
        raise RuntimeError(f"Gemini generateContent returned {resp.status_code}: {_err_msg(resp)}")
    return _extract_gemini_image(resp.json())


