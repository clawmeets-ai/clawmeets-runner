"""
clawmeets/integrations/media/_lib.py

Provider-agnostic media generation — image, audio (TTS), and video — backed by
direct REST calls (httpx) to the selected provider. Supersedes the old
``image_gen`` integration.

Every entry function resolves its settings with the order
``flag > config-file section > env var > built-in default`` so an agent can run
fully from flags (ad-hoc), fully from the per-agent config
(``$CLAWMEETS_AGENT_DIR/skill-hub/configs/media.json``, one section per
modality), or any mix. Generated bytes are written atomically under the
resolved ``output_dir`` and the absolute path is returned so consumers pick it
up by path (e.g. ``update_file`` to surface it in chat).

Why not the LLM provider layer (opencode / openrouter)? ``LLMProvider.invoke``
returns text + token usage only — any returned media would be discarded. Media
generation lives here, in a direct-httpx skill. openrouter / opencode can still
be selected as a ``provider`` value wherever their REST endpoints return media.
"""
