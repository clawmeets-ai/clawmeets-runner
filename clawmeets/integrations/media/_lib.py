def _resolve_env(value: Any) -> Any:
    if not isinstance(value, str):
        return value
    if "${" not in value:
        return value
    out = value
    for key, val in os.environ.items():
        out = out.replace(f"${{{key}}}", val)
    return out


def _slug(text: str, max_len: int = 32) -> str:
    out = []
    last_dash = False
    for ch in text.lower():
        if ch.isalnum():
            out.append(ch)
            last_dash = False
        elif not last_dash:
            out.append("-")
            last_dash = True
    s = "".join(out).strip("-")
    return (s[:max_len] or "media").rstrip("-")


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}.{int(time.time() * 1000)}")
    tmp.write_bytes(data)
    tmp.replace(path)


def _err_msg(resp: Any) -> str:
    try:
        j = resp.json()
        if isinstance(j, dict):
            err = j.get("error")
            if isinstance(err, dict):
                return err.get("message") or resp.text
            if isinstance(err, str):
                return err
            return j.get("detail") or resp.text
    except Exception:
        pass
    return resp.text


def _data_uri(image_path: str) -> str:
    p = Path(image_path).expanduser()
    if not p.exists():
        raise RuntimeError(f"--input-image not found: {p}")
    mime, _ = mimetypes.guess_type(str(p))
    mime = mime or "image/png"
    b64 = base64.b64encode(p.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{b64}"


def _load_input_image(path: str) -> tuple[bytes, str, str]:
    """Read a local image into ``(raw_bytes, mime, filename)``.

    Raises ``RuntimeError`` if the path is missing or resolves to a non-image
    mime type. Shared by both image-edit backends.
    """
    p = Path(path).expanduser()
    if not p.exists():
        raise RuntimeError(f"--input-image not found: {p}")
    mime, _ = mimetypes.guess_type(str(p))
    mime = mime or "image/png"
    if not mime.startswith("image/"):
        raise RuntimeError(
            f"--input-image {p} is not an image (guessed mime {mime!r}); "
            "pass a PNG/JPEG/WebP file.")
    return p.read_bytes(), mime, p.name


def _pcm_to_wav(pcm: bytes, rate: int, channels: int = 1, sampwidth: int = 2) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(sampwidth)
        w.setframerate(rate)
        w.writeframes(pcm)
    return buf.getvalue()


def _ext_from_url(url: str, fallback: str) -> str:
    path = url.split("?", 1)[0]
    dot = path.rsplit(".", 1)
    if len(dot) == 2 and 1 <= len(dot[1]) <= 5 and dot[1].isalnum():
        return dot[1].lower()
    return fallback


def _maybe_number(value: str) -> Any:
    try:
        if "." in value:
            return float(value)
        return int(value)
    except (TypeError, ValueError):
        return value


# --------------------------------------------------------------------------- #
# Config resolution: flag > config-file section > env > default
# --------------------------------------------------------------------------- #
def load_config(modality: str, config_file: str, overrides: dict) -> dict:
    """Resolve the effective settings for one modality.

    ``overrides`` are CLI flag values; only non-empty ones take effect. Missing
    config file is fine — flags + env can fully supply the settings. Raises
    ``RuntimeError`` on an unsupported provider, a missing api_key, or an
    unresolvable output_dir.
    """
    if modality not in MODALITIES:
        raise RuntimeError(f"unknown modality {modality!r}; choose one of {MODALITIES}")

    section: dict = {}
    path = resolve_skill_config_path("media", config_file)
    if path:
        p = Path(path).expanduser()
        if p.exists():
            raw = p.read_text()
            try:
                from clawmeets.utils.jsonc import parse_jsonc
                full = parse_jsonc(raw)
            except Exception:
                full = json.loads(raw)
            if not isinstance(full, dict):
                raise RuntimeError(
                    f"media config must be a JSON object, got {type(full).__name__}"
                )
            sec = full.get(modality)
            if isinstance(sec, dict):
                section = sec

    merged = dict(section)
    for key, val in overrides.items():
        if val not in (None, ""):
            merged[key] = val

    provider = (merged.get("provider") or DEFAULT_PROVIDER[modality]).strip()
    if provider not in PROVIDERS[modality]:
        raise RuntimeError(
            f"media {modality}: `provider` {provider!r} is not supported; "
            f"choose one of: {sorted(PROVIDERS[modality])}"
        )

    api_key = _resolve_env(merged.get("api_key"))
    if not isinstance(api_key, str) or not api_key or api_key.startswith("${"):
        env_name = PROVIDER_ENV.get(provider, "")
        api_key = os.environ.get(env_name, "") if env_name else ""
    if not api_key:
        env_name = PROVIDER_ENV.get(provider, "<provider key>")
        raise RuntimeError(
            f"media {modality}: no api_key for provider {provider!r}. Pass "
            f"--api-key, set `api_key` in the media config, or export "
            f"{env_name} on the runner before `clawmeets start`."
        )

    output_dir_raw = _resolve_env(merged.get("output_dir") or "")
    if not isinstance(output_dir_raw, str) or not output_dir_raw or "${" in output_dir_raw:
        agent_dir = os.environ.get("CLAWMEETS_AGENT_DIR", "")
        if agent_dir:
            output_dir_raw = str(Path(agent_dir) / "media" / modality)
        else:
            raise RuntimeError(
                f"media {modality}: `output_dir` is unset/unresolved and "
                "CLAWMEETS_AGENT_DIR is not in the env. Pass --output-dir or set "
                "output_dir in the config."
            )
    output_dir = Path(output_dir_raw).expanduser()

    return {
        "modality": modality,
        "provider": provider,
        "api_key": api_key,
        "model": (merged.get("model") or DEFAULT_MODELS[(modality, provider)]).strip(),
        "output_dir": output_dir,
        "timeout_seconds": float(merged.get("timeout_seconds") or DEFAULT_TIMEOUTS[modality]),
        "poll_interval_seconds": float(merged.get("poll_interval_seconds") or 5),
        # modality-specific defaults pulled from the config section
        "default_size": merged.get("default_size") or "",
        "default_quality": merged.get("default_quality") or "",
        "voice": merged.get("voice") or "",
        "audio_format": merged.get("audio_format") or merged.get("format") or "",
    }


def _finalize(cfg: dict, prompt: str, data: bytes, ext: str, extra: dict) -> dict:
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    digest = hashlib.sha256(prompt.encode("utf-8")).hexdigest()[:8]
    filename = f"{ts}-{_slug(prompt)}-{digest}.{ext}"
    out_path = (cfg["output_dir"] / filename).resolve()
    _atomic_write_bytes(out_path, data)
    result = {
        "media_path": str(out_path),
        f"{cfg['modality']}_path": str(out_path),
        "media_type": cfg["modality"],
        "prompt_used": prompt,
        "provider": cfg["provider"],
        "model": cfg["model"],
        "generated_at": ts,
    }
    result.update(extra)
    return result


